CREATE TABLE clients (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  phone VARCHAR(20) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE devices (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  model VARCHAR(100) NOT NULL,
  serial_number VARCHAR(100) NOT NULL,
  client_id INT UNSIGNED NOT NULL,
  CONSTRAINT fk_devices_client FOREIGN KEY (client_id) REFERENCES clients(id)
) ENGINE=InnoDB;

CREATE TABLE masters (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  specialization VARCHAR(100) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE requests (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  description TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'new',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  client_id INT UNSIGNED NOT NULL,
  device_id INT UNSIGNED NOT NULL,
  master_id INT UNSIGNED,
  CONSTRAINT fk_requests_client FOREIGN KEY (client_id) REFERENCES clients(id),
  CONSTRAINT fk_requests_device FOREIGN KEY (device_id) REFERENCES devices(id),
  CONSTRAINT fk_requests_master FOREIGN KEY (master_id) REFERENCES masters(id)
) ENGINE=InnoDB;
